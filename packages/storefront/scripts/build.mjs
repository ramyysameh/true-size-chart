// Builds the theme app extension assets. Deterministic: same input, byte-identical output (no timestamps).
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const ext = join(pkg, '..', '..', 'extensions', 'true-size-chart');
const shared = { bundle: true, minify: true, target: 'es2020', legalComments: 'none', logLevel: 'warning' };

mkdirSync(join(ext, 'assets'), { recursive: true });
mkdirSync(join(ext, 'snippets'), { recursive: true });

await build({
  ...shared,
  entryPoints: [join(pkg, 'src', 'index.ts')],
  format: 'iife',
  outfile: join(ext, 'assets', 'tsc-finder.js'),
});

await build({
  ...shared,
  entryPoints: [join(pkg, 'src', 'styles', 'finder.css')],
  outfile: join(ext, 'assets', 'tsc-finder.css'),
});

// The loader is inlined into the page, so it is built in memory and wrapped as a Liquid snippet.
const loader = await build({
  ...shared,
  stdin: {
    contents: "import { boot } from './loader'; boot(document, window);",
    resolveDir: join(pkg, 'src'),
    sourcefile: 'loader-entry.ts',
    loader: 'ts',
  },
  format: 'iife',
  write: false,
});
const code = loader.outputFiles[0].text.trim();
for (const bad of ['{% endraw', '</script']) {
  if (code.includes(bad)) throw new Error(`Minified loader contains "${bad}"; it cannot be inlined safely.`);
}
writeFileSync(
  join(ext, 'snippets', 'tsc-loader.liquid'),
  `{%- doc -%} Generated by packages/storefront/scripts/build.mjs. Do not edit. {%- enddoc -%}\n<script>{% raw %}${code}{% endraw %}</script>\n`,
);
