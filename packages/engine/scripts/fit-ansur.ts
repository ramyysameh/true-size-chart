// Fits girth/inseam = a + b·heightCm + c·weightKg + d·BMI per sex on ANSUR II
// and writes src/coefficients.ts. Run `node scripts/fetch-ansur.mjs` first.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ols } from '../src/ols.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// ANSUR II units: lengths in mm, weightkg in tenths of a kilogram.
const COLUMNS = {
  chest: 'chestcircumference',
  waist: 'waistcircumference',
  hip: 'buttockcircumference',
  inseam: 'crotchheight',
} as const;
// Female chest is set lower: bust varies with more than height and weight, which the finder's Chest shape step compensates for.
const MIN_R2 = { male: { chest: 0.75, waist: 0.75, hip: 0.75, inseam: 0.6 }, female: { chest: 0.7, waist: 0.75, hip: 0.75, inseam: 0.6 } } as const;

type Dim = keyof typeof COLUMNS;
const out: Record<string, Record<string, unknown>> = {};
let failed = false;

for (const sex of ['male', 'female'] as const) {
  const lines = readFileSync(join(root, 'data', `ansur2-${sex}.csv`), 'latin1').split(/\r?\n/).filter(Boolean);
  const header = lines[0]!.split(',');
  const col = (name: string) => {
    const i = header.indexOf(name);
    if (i < 0) throw new Error(`Column ${name} missing in ${sex} file`);
    return i;
  };
  const rows = lines.slice(1).map((l) => l.split(','));
  const heightCm = rows.map((r) => Number(r[col('stature')]) / 10);
  const weightKg = rows.map((r) => Number(r[col('weightkg')]) / 10);
  const X = rows.map((_, n) => {
    const h = heightCm[n]!;
    const w = weightKg[n]!;
    return [1, h, w, w / (h / 100) ** 2];
  });

  out[sex] = {};
  for (const dim of Object.keys(COLUMNS) as Dim[]) {
    const i = col(COLUMNS[dim]);
    const y = rows.map((r) => Number(r[i]) / 10);
    const { beta, r2 } = ols(X, y);
    const [a, b, c, d] = beta.map((v) => Number(v.toFixed(5)));
    out[sex]![dim] = { a, b, c, d, r2: Number(r2.toFixed(3)), n: rows.length };
    const ok = r2 >= MIN_R2[sex][dim];
    const rmse = Math.sqrt(y.reduce((acc, v, n) => acc + (v - X[n]!.reduce((p, x, j) => p + x * beta[j]!, 0)) ** 2, 0) / y.length);
    if (!ok) failed = true;
    console.log(`${sex.padEnd(6)} ${dim.padEnd(6)} r2=${r2.toFixed(3)} rmse=${rmse.toFixed(1)}cm n=${rows.length}${ok ? '' : '  BELOW THRESHOLD'}`);
  }
}

if (failed) {
  console.error('A fit is below its r2 threshold; coefficients.ts was not written.');
  process.exit(1);
}

writeFileSync(
  join(root, 'src', 'coefficients.ts'),
  `// Generated by scripts/fit-ansur.ts from ANSUR II (public domain). Do not edit by hand.
// girth or inseam (cm) = a + b·heightCm + c·weightKg + d·BMI
import type { Sex } from './types';

export interface Coefficient { a: number; b: number; c: number; d: number; r2: number; n: number }
export type BodyDim = 'chest' | 'waist' | 'hip' | 'inseam';

export const COEFFS: Record<Sex, Record<BodyDim, Coefficient>> = ${JSON.stringify(out, null, 2)};
`,
);
console.log('wrote src/coefficients.ts');
